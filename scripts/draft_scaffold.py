def render_scaffold(sec_key, topic=None):
    cfg = SCAFFOLDS.get(sec_key)
    if not cfg:
        return f"未识别的章节类型：{sec_key}。支持列表：{list(SCAFFOLDS.keys())}"
    lines = []
    lines.append("=" * 70)
    lines.append(f"《图书馆学研究》规范脚手架 —— {cfg['title']}")
    lines.append("=" * 70)
    lines.append(f"· 目标篇幅：{cfg['target_chars']}")
    lines.append(f"· 建议句均：{cfg['sent_mean']}")
    lines.append(f"· 推荐连接词：{cfg['key_conn']}")
    lines.append(f"· 体例红线：{cfg['red_lines']}")
    lines.append("-" * 70)
    lines.append("【地道学术骨架（填空即用）】：\n")
    for s in cfg["template"]:
        if topic:
            s = s.replace("[核心主题词]", topic).replace("[领域基础工作/服务模式探索]", f"{topic}相关探索")
        lines.append(s)
    lines.append("\n" + "=" * 70)
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="《图书馆学研究》分段骨架与句式脚手架生成器")
    parser.add_argument("--section", "-s", choices=list(SCAFFOLDS.keys()),
                        help="指定章节: intro(引言) / design(方法) / finding(结果差距) / policy(对策) / ending(结语)")
    parser.add_argument("--topic", "-t", default=None, help="可选：论文主题词，自动填入骨架槽位")
    parser.add_argument("--all", "-a", action="store_true", help="输出全套五段核心骨架")

    args = parser.parse_args()
    if not args.section and not args.all:
        parser.print_help()
        sys.exit(0)

    if args.all:
        for k in SCAFFOLDS:
            print(render_scaffold(k, topic=args.topic))
            print("\n")
    else:
        print(render_scaffold(args.section, topic=args.topic))


if __name__ == "__main__":
    main()
